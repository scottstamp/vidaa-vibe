#!/bin/bash
# Build native/ for the 58A51HUV: armv7 hard-float, glibc 2.21, dynamically
# linked against the TV's own DirectFB 1.4.2.
#
# Run in WSL (the PC's WSL cannot reach the TV; deploy from Windows):
#   wsl.exe -e bash native/build.sh
#
# Needs:
#   ZIG          zig 0.17 (default: ~/alvidaa-build/zig/zig)
#   .deps/sysroot/vendor/lib/directfb/  pulled from the TV by pull-sysroot.sh
# Fetches DirectFB-1.4.2 once for its public headers only (no code from it
# is built or run) and checks its sha256.
set -euo pipefail
cd "$(dirname "$0")"
HERE=$PWD
ZIG=${ZIG:-$HOME/alvidaa-build/zig/zig}
DEPS=$HERE/.deps
OUT=$HERE/out
DFB_TGZ=DirectFB-1.4.2.tar.gz
DFB_URL=https://sources.buildroot.net/$DFB_TGZ
DFB_SHA=051847e21e88a9c32ee78f8920014602d8b21928602075c5266433cd58addbc6
SYSLIB=$DEPS/sysroot/vendor/lib/directfb

mkdir -p "$DEPS" "$OUT"

# --- DirectFB public headers
INC=$DEPS/directfb-include
if [ ! -f "$INC/directfb.h" ]; then
    if [ ! -f "$DEPS/$DFB_TGZ" ]; then
        curl -fsSL -o "$DEPS/$DFB_TGZ.part" "$DFB_URL"
        mv "$DEPS/$DFB_TGZ.part" "$DEPS/$DFB_TGZ"
    fi
    echo "$DFB_SHA  $DEPS/$DFB_TGZ" | sha256sum -c -
    rm -rf "$DEPS/dfb-src" && mkdir -p "$DEPS/dfb-src"
    tar -xzf "$DEPS/$DFB_TGZ" -C "$DEPS/dfb-src" \
        DirectFB-1.4.2/include DirectFB-1.4.2/lib/direct
    S=$DEPS/dfb-src/DirectFB-1.4.2
    mkdir -p "$INC/direct"
    cp "$S"/include/*.h "$INC/"
    cp "$S"/lib/direct/*.h "$INC/direct/"
    # build.h is generated by configure; values for a release build
    cat > "$INC/direct/build.h" <<'EOF'
#ifndef __DIRECT__BUILD_H__
#define __DIRECT__BUILD_H__
#define DIRECT_BUILD_DEBUG   (0)
#define DIRECT_BUILD_DEBUGS  (0)
#define DIRECT_BUILD_TRACE   (0)
#define DIRECT_BUILD_TEXT    (1)
#define DIRECT_BUILD_GETTID  (1)
#define DIRECT_BUILD_NETWORK (0)
#define DIRECT_BUILD_STDBOOL (1)
#endif
EOF
    # the vendor build's interface layouts differ from upstream 1.4.2
    python3 "$HERE/tools/mstar_headers.py" "$INC"
fi

# --- link stubs: the TV's libraries under their sonames
[ -f "$SYSLIB/libdirectfb-1.4.so.0.2.0" ] || {
    echo "missing $SYSLIB: run native/pull-sysroot.sh from Windows first" >&2; exit 1; }
LIB=$DEPS/lib
mkdir -p "$LIB"
for n in directfb direct fusion; do
    ln -sf "$SYSLIB/lib$n-1.4.so.0.2.0" "$LIB/lib$n-1.4.so.0"
    ln -sf "$SYSLIB/lib$n-1.4.so.0.2.0" "$LIB/lib$n.so"
done

CFLAGS="-target arm-linux-gnueabihf.2.21 -mcpu=cortex_a7 -O2 -g0 -std=gnu11
        -Wall -Wextra -Wno-unused-parameter -Wno-missing-field-initializers
        -fno-sanitize=undefined -D_REENTRANT -I$INC"
# The TV's libdirectfb pulls in libstdc++, libfreetype, libz from its own
# lib dirs at run time; they are not needed to link.
COMMON_LD="-Wl,--dynamic-linker=/lib/ld-linux.so.3 -s"
LDFLAGS="-L$LIB -ldirectfb -ldirect -lfusion -lpthread -Wl,--allow-shlib-undefined $COMMON_LD"

"$ZIG" cc $CFLAGS -o "$OUT/vibe" src/vibe.c src/common.c $LDFLAGS
# vibe-model dlopens the vendor's libbizAgent.so at run time: libc + libdl only
"$ZIG" cc $CFLAGS -o "$OUT/vibe-model" src/vibe-model.c src/biz.c src/common.c -ldl $COMMON_LD
# the app: DirectFB at link time, the model facade by dlopen
# app_man client tool (dlopens /basic/libgam_client.so)
"$ZIG" cc $CFLAGS -o "$OUT/vibe-gam" src/vibe-gam.c src/gam.c src/common.c -ldl $COMMON_LD
"$ZIG" cc $CFLAGS -o "$OUT/vibe-ui" src/vibe-ui.c src/biz.c src/gam.c src/common.c -ldl $LDFLAGS
ls -la "$OUT/vibe" "$OUT/vibe-model" "$OUT/vibe-ui" "$OUT/vibe-gam"
